"""Candidate-local native starting curves prepared before any scan exists.

The bank accelerates selection of optimizer starts only. It neither
interpolates diffraction curves nor limits the continuous refinement space.
Every curve is generated by GSAS-II at the exact stored parameters.
"""
import hashlib,inspect,json,time
from collections import OrderedDict
import threading
import zipfile
import zlib
from pathlib import Path
import numpy as np
from .structural_start_bank import multiscale_starts,joint_cell_starts


def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def array_hash(value):return hashlib.sha256(np.ascontiguousarray(value).tobytes()).hexdigest()


# A private in-process record of banks actually built by this native engine.
# It is never serialized or accepted from an uploaded manifest. Only hashes
# are retained; curve arrays remain in bounded files, not a growing RAM cache.
_native_banks=OrderedDict()
_native_bank_lock=threading.Lock()


def _bank_key(source,path,receipt_path=None):
    from ...symmetry.contracts import digest
    path=Path(path);receipt_path=Path(receipt_path) if receipt_path is not None else path.with_suffix('.json')
    return digest(dict(context=context(source),bank_sha256=sha(path),receipt_sha256=sha(receipt_path)))


def _remember_native(source,path):
    receipt=read_bank_receipt(path)
    if receipt.get('curve_role','native')!='native' or receipt.get('interpolation') is not False:
        raise ValueError('Starting proposals cannot acquire native-bank authority')
    key=_bank_key(source,path)
    with _native_bank_lock:
        _native_banks[key]=True;_native_banks.move_to_end(key)
        while len(_native_banks)>64:_native_banks.popitem(last=False)


def native_in_this_process(source,path,receipt_path=None):
    key=_bank_key(source,path,receipt_path)
    with _native_bank_lock:
        if key not in _native_banks:return False
        _native_banks.move_to_end(key)
    return True


def context(source):
    from gpx_recipe.symmetry.compiler import package_signature
    implementation=lambda: (package_signature(), None)
    from .full_mode_slice import FullModeSlice
    from .native_fast_candidate import NativeFastCandidate
    from gpx_recipe.live.native_profile import NativeReducedProfile
    implementations=[Path(__file__),Path(inspect.getfile(multiscale_starts)),Path(inspect.getfile(FullModeSlice)),
        Path(inspect.getfile(NativeFastCandidate)),Path(inspect.getfile(NativeReducedProfile))]
    from gpx_recipe.preparation.structural_identity import structural_physics_identity
    return dict(schema='native-start-bank/v2',physics_sha256=structural_physics_identity(source),
        scientific_implementation_sha256=implementation()[0],
        native_powder_sources_sha256={name:sha(module.__file__) for name,module in [('GSASIIstrMath',source.fast.native.math),('GSASIIpwd',source.fast.native.math.G2pwd),('pypowder',source.fast.native.math.G2pwd.pyd)]},
        radii=source.radii.tolist(),lift_sha256=array_hash(source.lift),x_sha256=array_hash(source.fast.x),
        chemistry_fingerprint=source.chemistry.fingerprint,
        implementations={p.name:sha(p) for p in implementations},mode_dimensions=source.mode_dimensions,cell_dimensions=source.cell_dimensions,
        anchor='zero cell offset',likelihood_or_observations_used=False)


def policy_points(source,policy):
    if policy=='multiscale_v1':return multiscale_starts(source.mode_dimensions,source.cell_dimensions)
    if policy=='joint_cell_v1':return joint_cell_starts(source.mode_dimensions,source.cell_dimensions)
    raise ValueError('Unknown prepared starting-point policy')


def build(source,path,policy='multiscale_v1',*,reuse_fixed_cell_profiles=False):
    if type(reuse_fixed_cell_profiles) is not bool:raise TypeError('Fixed-cell reuse must be an explicit boolean')
    if reuse_fixed_cell_profiles:
        from .native_bank_reuse import build_reusing_profiles
        return build_reusing_profiles(source,path,policy=policy)
    return _construct(source,path,policy=policy)


def _construct(source,path,policy='multiscale_v1',*,proposal_renderer=None):
    """Shared complete portfolio; proposal rendering cannot grant native origin."""
    path=Path(path)
    if path.exists() or path.with_suffix('.json').exists():raise ValueError('Start-bank artifacts are immutable; use a new path')
    evaluate=source.native if proposal_renderer is None else proposal_renderer
    start=time.perf_counter();identity=context(source);points=policy_points(source,policy)
    feasible=[];curves=[];selected=[]
    for index,point in enumerate(points):
        allowed=bool(np.isfinite(source.chemistry.log_kernel((point*source.radii)[None,:])[0]));feasible.append(allowed)
        if not allowed:continue
        curves.append(evaluate(point*source.radii));selected.append(index)
    if not curves:raise ValueError('No chemically feasible native starting curves')
    # Proposal scales can be chosen before data exist. Their native finite
    # differences remain proposals, not a surrogate likelihood or covariance.
    from .reference_secants import select_secant_steps
    began=time.perf_counter();origin=np.zeros(len(source.radii));parent=evaluate(origin)
    weight=1/np.sqrt(np.maximum(abs(parent),max(np.max(abs(parent))*1e-4,1e-30)))
    def allowed(p):
        return np.isfinite(p).all() and np.all(abs(p)<=1.) and bool(np.isfinite(source.chemistry.log_kernel((p*source.radii)[None,:])[0]))
    try:
        steps,details=select_secant_steps(lambda p:evaluate(p*source.radii)*weight,origin,
            range(source.mode_dimensions,len(source.radii)),allowed=allowed,scales=(.0005,.002,.008,.032,.128))
        proposal=dict(state='prepared',details=details)
    except ValueError as exc:
        steps=np.full(len(source.radii),.002);proposal=dict(state='fixed_default_fallback',reason=str(exc),details=[])
    proposal.update(seconds=time.perf_counter()-began,derivative_qualified=False,observations_used=False,
        weighting='inverse square root of parent profile magnitude with 1e-4 peak floor; proposal heuristic only',anchor='parent geometry')
    if context(source)!=identity:raise ValueError('Fixed native context changed while preparing starting curves')
    from ...preparation.structural_nuisance import reference
    normalization=reference(source)
    if context(source)!=identity:raise ValueError('Fixed native context changed during background factorization')
    extra={} if normalization is None else {'reference_background':normalization[1]}
    path.parent.mkdir(parents=True,exist_ok=True)
    np.savez_compressed(path,points=points[selected],curves=np.asarray(curves),original_indices=np.asarray(selected),feasible=np.asarray(feasible),x=source.fast.x,proposal_cell_steps=steps,**extra)
    native=proposal_renderer is None
    receipt=dict(context=identity,policy=policy,sha256=sha(path),seconds=time.perf_counter()-start,proposed_points=len(points),native_curves=len(curves) if native else 0,
        chemically_infeasible_points=int(np.count_nonzero(~np.asarray(feasible))),bytes=path.stat().st_size,proposal_step_selection=proposal,
        interpolation=not native,curve_role='native' if native else 'starting_proposals',
        starting_curves=len(curves),shared_across_candidates=False,
        scope='Optimizer starts and optional proposal step sizes; all allowed continuous parameters remain free; fitted objectives remain original native calculations')
    if normalization is not None:receipt['affine_nuisance']=normalization[0]
    path.with_suffix('.json').write_text(json.dumps(receipt,indent=2)+'\n')
    if native:_remember_native(source,path)
    return receipt


def read_bank_receipt(path,receipt_path=None,*,maximum_bytes=None):
    """Bound and type-check optional imported arrays before native admission."""
    from ...live.array_limits import validate_npz
    path=Path(path);receipt_path=Path(receipt_path) if receipt_path is not None else path.with_suffix('.json')
    if receipt_path.stat().st_size>4*1024*1024:raise ValueError('Native start-bank metadata exceeds its budget')
    try:
        validate_npz(path,maximum_bytes=maximum_bytes)
    except (zipfile.BadZipFile,zlib.error,NotImplementedError) as exc:
        raise ValueError('Malformed or unsupported native start-bank archive') from exc
    receipt=json.loads(receipt_path.read_text())
    if not isinstance(receipt,dict) or not isinstance(receipt.get('context'),dict):
        raise ValueError('Native start-bank receipt requires a typed physical context')
    return receipt


class OfflineNativeStartBank:
    CURVE_ROLE='native'
    def __init__(self,source,path,*,receipt_path=None):
        path=Path(path)
        receipt=read_bank_receipt(path,receipt_path)
        role=receipt.get('curve_role','native')
        if role!=self.CURVE_ROLE or receipt.get('interpolation') is not (role=='starting_proposals'):
            raise ValueError('Starting proposal and native-bank roles cannot be interchanged')
        if 'affine_nuisance' in receipt:
            from ...preparation.structural_nuisance import validate_context
            validate_context(receipt['affine_nuisance'])
        actual_context=context(source);same_context=receipt.get('context')==actual_context
        stored_context=receipt.get('context',{})
        # All non-physics dependencies (bounds, grid, native/package identity,
        # coordinate lift and chemistry) remain exact even for affine reuse.
        same_dependencies=({k:v for k,v in stored_context.items() if k!='physics_sha256'}==
            {k:v for k,v in actual_context.items() if k!='physics_sha256'})
        if (not same_context and (not same_dependencies or 'affine_nuisance' not in receipt)) or receipt.get('sha256')!=sha(path):
            raise ValueError('Native start-bank context or checksum changed; rebuild before using it')
        try:
            with np.load(path,allow_pickle=False) as stored:
                expected_names={'points','curves','original_indices','feasible','x','proposal_cell_steps'}
                if 'affine_nuisance' in receipt:expected_names.add('reference_background')
                if set(stored.files)!=expected_names:
                    raise ValueError('Invalid native start-bank array inventory')
                self.points=stored['points'].copy();self.curves=stored['curves'].copy();original=stored['original_indices'];feasible=stored['feasible'];x=stored['x']
                self.proposal_cell_steps=stored['proposal_cell_steps'].copy()
                reference_background=stored['reference_background'].copy() if 'affine_nuisance' in receipt else None
        except (zipfile.BadZipFile,zlib.error,NotImplementedError) as exc:
            raise ValueError('Malformed or unsupported native start-bank array payload') from exc
        expected=policy_points(source,receipt['policy'])
        if (self.points.ndim!=2 or self.points.shape[1]!=len(source.radii)
                or self.curves.shape!=(len(self.points),len(source.fast.x)) or not np.isfinite(self.curves).all()
                or feasible.dtype!=bool or original.dtype.kind not in 'iu' or original.ndim!=1
                or feasible.shape!=(len(expected),) or not np.array_equal(original,np.flatnonzero(feasible))
                or not np.array_equal(self.points,expected[original]) or not np.array_equal(x,source.fast.x)):
            raise ValueError('Invalid native start-bank shapes, coordinates or grid')
        count=receipt['native_curves'] if role=='native' else receipt.get('starting_curves')
        if count!=len(self.points) or (role=='starting_proposals' and receipt['native_curves']!=0):
            raise ValueError('Start-bank count disagrees with its curve role')
        actual=np.isfinite(source.chemistry.log_kernel((expected*source.radii)))
        if actual.shape!=feasible.shape or not np.array_equal(actual,feasible):
            raise ValueError('Native start-bank feasibility differs from the current complete domain')
        if self.proposal_cell_steps.shape!=source.radii.shape or not np.isfinite(self.proposal_cell_steps).all() or np.any(self.proposal_cell_steps<=0):raise ValueError('Invalid prepared proposal steps')
        self.nuisance_binding=None
        if reference_background is not None:
            if reference_background.shape!=x.shape or not np.isfinite(reference_background).all():
                raise ValueError('Invalid prepared native background shape')
            from ...preparation.structural_nuisance import affine_context,reference,rebind
            affine=affine_context(source)
            if affine is None or receipt['affine_nuisance'].get('shape_sha256')!=affine['shape_sha256']:
                raise ValueError('Native start-bank structural shape context changed; rebuild before using it')
            if not same_context:
                current=reference(source)
                self.nuisance_binding=rebind(self.curves,reference_background,receipt['affine_nuisance'],current[0],current[1])
            elif receipt['affine_nuisance']!=affine:
                raise ValueError('Native start-bank scale metadata differs from its exact context')
        self.proposal_cell_steps.flags.writeable=False
        self.points.flags.writeable=False;self.curves.flags.writeable=False;self.receipt=receipt

    def diagnostics(self):
        return dict({k:self.receipt[k] for k in ['sha256','policy','seconds','proposed_points','native_curves','chemically_infeasible_points','bytes','scope','proposal_step_selection']},
            curve_role=self.receipt.get('curve_role','native'),interpolation=self.receipt['interpolation'],
            starting_curves=self.receipt.get('starting_curves',self.receipt['native_curves']))

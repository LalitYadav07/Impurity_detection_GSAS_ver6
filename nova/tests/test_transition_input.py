from pathlib import Path

import numpy as np
import pytest
from radar_pd_nova.transition_input import reduced_observation


def product(tmp_path, *, multiplied=False, banks=(1,), truncate=False):
    x = np.geomspace(1000, 10000, 256)
    width = x * (
        2 * np.median(np.diff(x) / x[:-1]) / (2 + np.median(np.diff(x) / x[:-1]))
    )
    y = 20 + np.sin(x / 300) * 30
    lines = ["# File generated by Mantid:", "# Normalised to pCharge"]
    if multiplied:
        lines += ["# with Y multiplied by the bin widths"]
    for bank in banks:
        lines += [
            f"# Total flight path 40m, tth 90deg, DIFC {1000 * bank}",
            f"BANK {bank} 256 256 SLOG 1000 10000 .009 0 FXYE",
        ]
        for xx, yy, ww in zip(x, y, width):
            lines.append(
                f"{xx:.12g} {yy * ww if multiplied else yy:.12g} {ww if multiplied else 1:.12g}"
            )
    if truncate:
        lines.pop()
    path = tmp_path / "NOM_10.gsa"
    path.write_text("\n".join(lines) + "\n")
    scan = {
        "run_id": "NOM_10",
        "instrument": "NOM",
        "ipts": "IPTS-10",
        "run_number": 10,
        "bank": banks[0] if len(banks) == 1 else None,
        "source_path": str(path),
        "transition_source_root": str(tmp_path),
        "metadata": {"sample_id": "actual-sample"},
    }
    return scan, x, y


def test_declared_slog_bin_integrals_are_converted_with_the_calibrated_reader_convention(
    tmp_path,
):
    scan, x, y = product(tmp_path, multiplied=True)
    item = reduced_observation(scan)
    np.testing.assert_allclose(item.pattern.x, x, rtol=1e-10)
    np.testing.assert_allclose(item.pattern.intensity, y, rtol=1e-8, atol=1e-9)
    assert item.pattern.scope.intensity_semantics == "density_from_SLOG_bin_integrals"
    assert not any(item.pattern.valid[:2]) and not any(item.pattern.valid[-2:])
    assert np.any(item.pattern.intensity < 0)


def test_powgen_raw_reader_groups_qualified_mode_despite_motor_readback_jitter(tmp_path):
    from copy import deepcopy
    scan, _, _ = product(tmp_path)
    scan["instrument"] = "PG3"
    scan["metadata"]["powgen_setup"] = {
        "cycle": "2022-1_11A_CAL", "mode": "HR", "wavelength": 0.8, "frequency": 60,
        "calibration_files": ["cal.h5"], "characterization_files": ["HighRes.txt"],
        "grouping_files": [], "guide": -54.004}
    second = deepcopy(scan)
    second["metadata"]["powgen_setup"]["guide"] = -54.007
    first_scope = reduced_observation(scan).pattern.scope
    assert reduced_observation(second).pattern.scope == first_scope
    assert second["metadata"]["powgen_setup"]["guide"] == -54.007
    second["metadata"]["powgen_setup"]["characterization_files"] = ["different_HighRes.txt"]
    assert reduced_observation(second).pattern.scope != first_scope


def test_multibank_product_requires_an_explicit_bank(tmp_path):
    scan, _, _ = product(tmp_path, banks=(1, 2))
    with pytest.raises(ValueError, match="explicit physical bank"):
        reduced_observation(scan)
    scan["bank"] = 2
    assert reduced_observation(scan).pattern.scope.bank == "2"


def test_truncated_product_is_deferred_without_inventing_a_missing_phase(tmp_path):
    scan, _, _ = product(tmp_path, truncate=True)
    with pytest.raises(ValueError, match="truncated"):
        reduced_observation(scan)


def test_incomplete_later_bank_header_defers_the_whole_product(tmp_path):
    scan, _, _ = product(tmp_path)
    with Path(scan["source_path"]).open("a") as stream:
        stream.write("BANK\n")
    with pytest.raises(ValueError, match="header is incomplete"):
        reduced_observation(scan)


def test_source_paths_and_symlinks_cannot_escape_the_authorized_watch_root(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    scan, _, _ = product(source)
    other = tmp_path / "other"
    other.mkdir()
    scan["transition_source_root"] = str(other)
    with pytest.raises(ValueError, match="authorized watch"):
        reduced_observation(scan)
    link = other / "NOM_10.gsa"
    link.symlink_to(Path(scan["source_path"]))
    scan["source_path"] = str(link)
    with pytest.raises(ValueError, match="authorized watch"):
        reduced_observation(scan)


def test_undeclared_intensity_basis_is_preserved_instead_of_silently_dividing_by_bin_width(
    tmp_path,
):
    scan, _, y = product(tmp_path)
    item = reduced_observation(scan)
    np.testing.assert_allclose(item.pattern.intensity, y, rtol=1e-8, atol=1e-9)
    assert item.pattern.scope.intensity_semantics == "native_FXYE_unspecified"
